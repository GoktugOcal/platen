"""SANE configuration from PLATEN_* settings.

The entrypoint runs ``python -m app.container_setup`` once at start; the app
rewrites airscan.conf later when network discovery finds scanners.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from .config import Settings, parse_entries


def scanner_entries(scanners: str) -> list[tuple[str, str]]:
    """Manual PLATEN_SCANNERS entries as (name, url), unnamed ones numbered."""
    return [(name or f"Scanner {i}", url)
            for i, (name, url) in enumerate(parse_entries(scanners), start=1)]


def airscan_conf(entries: list[tuple[str, str]]) -> str:
    """sane-airscan config listing fixed devices.

    airscan's own discovery stays off: Platen discovers scanners itself
    (avahi over D-Bus is usually blocked in containers) and lists them here.
    """
    lines = [
        "# Generated by platen; set PLATEN_SCANNERS or use network discovery instead.",
        "[options]",
        "discovery = disable",
        "",
        "[devices]",
    ]
    for name, url in entries:
        protocol = "WSD" if "wsd" in url.lower() else "eSCL"
        label = re.sub(r'["\n=]', "", name)
        lines.append(f'"{label}" = {url}, {protocol}')
    return "\n".join(lines) + "\n"


def write_airscan_conf(sane_dir: Path, entries: list[tuple[str, str]]) -> bool:
    """Write airscan.conf if the content changed. Returns True when written."""
    path = sane_dir / "airscan.conf"
    content = airscan_conf(entries)
    if path.is_file() and path.read_text() == content:
        return False
    tmp = path.with_suffix(".tmp")
    tmp.write_text(content)
    tmp.replace(path)
    return True


def dll_conf(backends: str) -> str:
    names = [b.strip() for b in backends.split(",") if b.strip()]
    return "# Generated by platen; set PLATEN_SANE_BACKENDS to change.\n" + "\n".join(names) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sane-dir", default="/etc/sane.d", type=Path)
    args = parser.parse_args()
    settings = Settings()

    write_airscan_conf(args.sane_dir, scanner_entries(settings.scanners))
    (args.sane_dir / "dll.conf").write_text(dll_conf(settings.sane_backends))
    # Packages drop backend names into dll.d; keep only what was asked for.
    dll_d = args.sane_dir / "dll.d"
    if dll_d.is_dir():
        for entry in dll_d.iterdir():
            entry.unlink()


if __name__ == "__main__":
    main()
